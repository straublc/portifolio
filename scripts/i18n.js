const htmlLang = { pt: 'pt-br', en: 'en', es: 'es' };

function readSavedLang() {
  try {
    const saved = localStorage.getItem('lang');
    if (translations[saved]) return saved;
  } catch {}
  // Sem escolha salva, tenta o idioma do navegador
  const browser = (navigator.language || 'pt').slice(0, 2);
  return translations[browser] ? browser : 'pt';
}

function applyTranslations(lang, persist = true) {
  const t = translations[lang];
  if (!t) return;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const value = t[el.dataset.i18n];
    if (value) el.textContent = value;
  });

  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    const value = t[el.dataset.i18nAria];
    if (value) el.setAttribute('aria-label', value);
  });

  document.querySelectorAll('[data-i18n-alt]').forEach(el => {
    const value = t[el.dataset.i18nAlt];
    if (value) el.alt = value;
  });

  document.documentElement.lang = htmlLang[lang];
  document.title = t['meta.title'];
  document.querySelector('meta[name="description"]')?.setAttribute('content', t['meta.description']);

  document.querySelectorAll('[data-lang]').forEach(btn => {
    btn.setAttribute('aria-pressed', String(btn.dataset.lang === lang));
  });

  if (persist) {
    try { localStorage.setItem('lang', lang); } catch {}
  }
}

document.querySelectorAll('[data-lang]').forEach(btn => {
  btn.addEventListener('click', () => applyTranslations(btn.dataset.lang));
});

applyTranslations(readSavedLang(), false);
